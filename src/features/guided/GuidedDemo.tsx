import { useEffect, useMemo, useState } from 'react'
import { Link } from 'react-router-dom'
import { ArrowLeft, ArrowRight, Check, ChevronDown, Pause, Play, RotateCcw } from 'lucide-react'
import type { DemoScenario, IncidentAnalysis, RunResult } from '@faultline/engine'
import { SEVERITY_RANK } from '@faultline/engine'
import { cn } from '@/lib/utils'
import { CANONICAL_URL, IS_STANDALONE } from '@/lib/target'
import { LogoMark } from '../brand/Logo'
import { FaultlineTimeline } from '../story/FaultlineTimeline'
import { durationText, friendlyName, pctText, totalsAt } from '../story/plain'
import { SystemDiagram, type PartStatus } from '../story/SystemDiagram'
import { usePlayhead } from '../story/useWhatIf'
import { OutcomeComparison, WhatIfExplorer, type Outcome } from '../story/WhatIfExplorer'

export type GuidedStage = 0 | 1 | 2 | 3

interface Props {
  demo: DemoScenario
  analysis: IncidentAnalysis
  baseline: RunResult
  initialT?: number
  onEngineering: (state: { t: number; tab?: 'investigate' | 'simulate' | 'postmortem' }) => void
}

const STAGES = ['What happened?', 'Why did it happen?', 'What if?', 'Compare outcomes'] as const
const fmt = (sec: number) => `${Math.floor(sec / 60)}:${String(Math.floor(sec % 60)).padStart(2, '0')}`
const HEALTH_TO_STATUS: Record<string, PartStatus> = { healthy: 'ok', degraded: 'strained', recovering: 'strained', failing: 'failing' }

export function GuidedDemo({ demo, analysis, baseline, initialT = 0, onEngineering }: Props) {
  const [stage, setStage] = useState<GuidedStage>(0)
  const [outcome, setOutcome] = useState<Outcome | null>(null)
  const ph = usePlayhead(demo.scenario.durationSec, { speed: Math.max(18, demo.scenario.durationSec / 24) })
  useEffect(() => {
    if (initialT) ph.seek(initialT)
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [])

  const markers = demo.plain.story.map((b) => ({ atSec: b.atSec, label: b.text.split(/[.:,]/)[0], kind: b.kind }))
  const parts = useMemo(() => demo.scenario.model.services.map((s) => ({ id: s.id, name: friendlyName(s.id) })), [demo])
  const calls = demo.scenario.model.calls

  return (
    <div className="min-h-dvh bg-background">
      <header className="sticky top-0 z-30 border-b border-border bg-background/85 backdrop-blur-md">
        <div className="mx-auto flex h-16 max-w-6xl items-center gap-4 px-5">
          <Link to="/demo" className="inline-flex items-center gap-1.5 rounded-md text-muted-foreground hover:text-foreground" aria-label="All examples">
            <ArrowLeft className="size-4" /><LogoMark className="size-5" title="" />
          </Link>
          <nav aria-label="Steps" className="hidden flex-1 justify-center md:flex">
            <ol className="flex items-center gap-1">
              {STAGES.map((label, i) => {
                const reachable = i < 3 || outcome
                return (
                  <li key={label} className="flex items-center gap-1">
                    <button type="button" disabled={!reachable} onClick={() => setStage(i as GuidedStage)} aria-current={stage === i ? 'step' : undefined} className={cn('inline-flex h-9 items-center gap-2 rounded-full px-3 text-[14px] transition-colors disabled:opacity-40', stage === i ? 'bg-white text-foreground shadow-[0_0_0_1px_rgba(31,29,26,0.1)]' : 'text-muted-foreground hover:text-foreground')}>
                      <span className={cn('inline-flex size-5 items-center justify-center rounded-full text-[11px]', stage > i || (i === 3 && outcome && stage === 3) ? 'bg-foreground text-background' : stage === i ? 'bg-[var(--color-primary)] text-white' : 'bg-secondary text-muted-foreground')}>
                        {stage > i ? <Check className="size-3" /> : i + 1}
                      </span>
                      {label}
                    </button>
                    {i < 3 ? <span className="h-px w-4 bg-border" aria-hidden="true" /> : null}
                  </li>
                )
              })}
            </ol>
          </nav>
          <span className="flex-1 text-[14px] text-muted-foreground md:hidden">Step {stage + 1} of 4 · {STAGES[stage]}</span>
          <ModeSwitch mode="guided" onEngineering={() => onEngineering({ t: ph.t, tab: stage >= 2 ? 'simulate' : 'investigate' })} />
        </div>
      </header>

      <main className="mx-auto max-w-6xl px-5 pb-24 pt-10">
        <div className="mb-8 flex flex-wrap items-center gap-2">
          <span className="rounded-full bg-secondary px-2.5 py-1 text-[12.5px] text-muted-foreground">Synthetic example: generated by Faultline’s simulator</span>
          <span className="text-[12.5px] text-muted-foreground">{demo.title}</span>
        </div>

        {stage === 0 ? <WhatHappened demo={demo} analysis={analysis} baseline={baseline} ph={ph} parts={parts} calls={calls} markers={markers} onNext={() => setStage(1)} /> : null}
        {stage === 1 ? <WhyItHappened demo={demo} analysis={analysis} parts={parts} calls={calls} onNext={() => setStage(2)} onBack={() => setStage(0)} onEngineering={() => onEngineering({ t: ph.t, tab: 'investigate' })} /> : null}
        <div hidden={stage !== 2}>
          <section aria-labelledby="whatif-h">
            <p className="fl-eyebrow">Step 3</p>
            <h1 id="whatif-h" className="mt-3 text-[34px] font-normal leading-[1.1] text-foreground sm:text-[44px]">What would you have done differently?</h1>
            <p className="mt-4 max-w-2xl text-[16.5px] leading-relaxed text-muted-foreground">Choose a decision and when to make it. Faultline runs the whole system forward again from that moment, using the same model that produced this incident.</p>
            <div className="mt-10">
              <WhatIfExplorer
                scenario={demo.scenario}
                choices={demo.choices}
                markers={markers}
                defaultDecisionSec={demo.suggested.atSec}
                baseline={baseline}
                hideComparison
                compactHeader
                onResult={(o) => {
                  setOutcome(o)
                  setStage(3)
                  window.scrollTo({ top: 0, behavior: 'smooth' })
                }}
              />
            </div>
          </section>
        </div>
        {stage === 3 && outcome ? (
          <CompareOutcomes
            demo={demo}
            outcome={outcome}
            markers={markers}
            onTryAnother={() => setStage(2)}
            onEngineering={(tab) => onEngineering({ t: outcome.atSec, tab })}
          />
        ) : null}
      </main>
    </div>
  )
}

export function ModeSwitch({ mode, onEngineering, onGuided }: { mode: 'guided' | 'engineering'; onEngineering?: () => void; onGuided?: () => void }) {
  return (
    <div className="flex items-center rounded-full bg-secondary p-0.5 text-[13px]" role="group" aria-label="View">
      <button type="button" aria-pressed={mode === 'guided'} onClick={onGuided} className={cn('h-8 rounded-full px-3', mode === 'guided' ? 'bg-white text-foreground shadow-sm' : 'text-muted-foreground hover:text-foreground')}>Guided</button>
      <button type="button" aria-pressed={mode === 'engineering'} onClick={onEngineering} className={cn('h-8 rounded-full px-3', mode === 'engineering' ? 'bg-white text-foreground shadow-sm' : 'text-muted-foreground hover:text-foreground')}>Engineering</button>
    </div>
  )
}

type PH = ReturnType<typeof usePlayhead>

function WhatHappened({ demo, analysis, baseline, ph, parts, calls, markers, onNext }: { demo: DemoScenario; analysis: IncidentAnalysis; baseline: RunResult; ph: PH; parts: Array<{ id: string; name: string }>; calls: Array<{ from: string; to: string }>; markers: Array<{ atSec: number; label: string; kind: 'change' | 'strain' | 'impact' | 'response' | 'recovery' }>; onNext: () => void }) {
  const wall = demo.baseTime + ph.t * 1000
  const state = useMemo(() => analysis.replay.stateAt(wall), [analysis.replay, wall])
  const status: Record<string, PartStatus> = {}
  for (const p of parts) status[p.id] = HEALTH_TO_STATUS[state.services[p.id]?.health ?? 'healthy'] ?? 'ok'
  const totals = totalsAt(baseline.samples, ph.t)
  const current = [...demo.plain.story].reverse().find((b) => b.atSec <= ph.t)
  const s = baseline.summary
  return (
    <section aria-labelledby="what-h">
      <p className="fl-eyebrow">Step 1</p>
      <h1 id="what-h" className="mt-3 max-w-3xl text-[34px] font-normal leading-[1.1] text-foreground sm:text-[44px]">{demo.plain.headline}</h1>
      <p className="mt-4 max-w-2xl text-[16.5px] leading-relaxed text-muted-foreground">
        Over about {Math.round(demo.scenario.durationSec / 60)} minutes, {pctText(1 - s.successRate)} of customer requests failed ({(s.failed + s.rateLimited).toLocaleString()} in total), and {s.recovered ? `service took ${durationText(s.timeToRecoverySec)} to recover once it broke` : 'service had not fully recovered by the end'}. Press replay to watch it unfold.
      </p>

      <div className="mt-10 grid gap-8 lg:grid-cols-[minmax(0,360px)_1fr]">
        <ol className="space-y-1" aria-label="What happened, in order">
          {demo.plain.story.map((b) => {
            const active = current === b
            const past = b.atSec <= ph.t
            return (
              <li key={b.atSec + b.text}>
                <button type="button" onClick={() => ph.seek(b.atSec)} className={cn('grid w-full grid-cols-[44px_1fr] gap-3 rounded-xl px-3 py-3 text-left transition-colors', active ? 'bg-white shadow-[0_0_0_1px_rgba(31,29,26,0.08)]' : 'hover:bg-white/60')}>
                  <span className={cn('pt-0.5 font-mono text-[12.5px] tabular', past ? 'text-foreground' : 'text-faint')}>{fmt(b.atSec)}</span>
                  <span className={cn('text-[15px] leading-snug', past ? 'text-foreground' : 'text-muted-foreground')}>
                    {b.kind === 'impact' ? <span className="mr-1.5 inline-block size-2 rounded-full bg-[var(--color-fault)] align-middle" /> : null}
                    {b.text}
                  </span>
                </button>
              </li>
            )
          })}
        </ol>
        <div className="min-w-0">
          <div className="fl-frame">
            <div className="fl-frame-inner bg-card p-5 sm:p-6">
              <SystemDiagram parts={parts.map((p) => ({ ...p, detail: demo.plain.parts[p.id] }))} calls={calls} status={status} dense={parts.length > 4} />
              <div className="mt-5 grid gap-4 sm:grid-cols-3">
                <Stat label="Requests failing right now" value={pctText(totals.rate)} tone={totals.rate >= 0.2 ? 'fault' : totals.rate >= 0.01 ? 'warn' : 'ok'} />
                <Stat label="Failed so far" value={totals.failed.toLocaleString()} tone={totals.failed ? 'fault' : 'ok'} />
                <Stat label="Succeeded so far" value={totals.ok.toLocaleString()} tone="ok" />
              </div>
              <div className="mt-5">
                <FaultlineTimeline compact durationSec={demo.scenario.durationSec} baseline={baseline.samples} t={ph.t} onSeek={ph.seek} markers={markers} />
              </div>
              <div className="mt-4 flex flex-wrap items-center gap-2">
                <button type="button" onClick={ph.playing ? ph.pause : ph.play} className="fl-cta inline-flex h-10 items-center gap-2 rounded-xl px-4 text-[14.5px] font-medium">
                  {ph.playing ? <Pause className="size-4" /> : <Play className="size-4" />} {ph.playing ? 'Pause' : 'Replay failure'}
                </button>
                <button type="button" onClick={ph.replay} className="inline-flex h-10 items-center gap-1.5 rounded-xl px-3 text-[14px] text-muted-foreground hover:text-foreground"><RotateCcw className="size-4" /> From the start</button>
                <span className="ml-auto font-mono text-[13px] tabular text-muted-foreground">{fmt(ph.t)}</span>
              </div>
            </div>
          </div>
          {current ? <p className="mt-4 text-[15px] leading-relaxed text-foreground" aria-live="polite">{current.text}</p> : null}
        </div>
      </div>
      <NextBar label="Why did it happen?" onNext={onNext} />
    </section>
  )
}

function WhyItHappened({ demo, analysis, parts, calls, onNext, onBack, onEngineering }: { demo: DemoScenario; analysis: IncidentAnalysis; parts: Array<{ id: string; name: string }>; calls: Array<{ from: string; to: string }>; onNext: () => void; onBack: () => void; onEngineering: () => void }) {
  const [open, setOpen] = useState(false)
  const top = analysis.hypotheses[0]
  const events = analysis.dataset.events
  const byId = useMemo(() => new Map(events.map((e) => [e.id, e])), [events])
  const topEvent = top ? byId.get(top.eventId) : undefined
  const entry = demo.scenario.model.entry
  const firstCustomerError = events.find((e) => e.service === entry && SEVERITY_RANK[e.severity] >= 3)
  const lead = topEvent && firstCustomerError ? Math.round((firstCustomerError.ts - topEvent.ts) / 1000) : null
  const affected = new Set(events.filter((e) => SEVERITY_RANK[e.severity] >= 3).map((e) => e.service))
  const status: Record<string, PartStatus> = {}
  for (const p of parts) status[p.id] = p.id === top?.service ? 'failing' : affected.has(p.id) ? 'strained' : 'ok'
  const edges = top ? analysis.correlation.edges.filter((e) => e.source === top.eventId).sort((a, b) => b.score - a.score).slice(0, 6) : []

  return (
    <section aria-labelledby="why-h">
      <p className="fl-eyebrow">Step 2</p>
      <h1 id="why-h" className="mt-3 max-w-3xl text-[34px] font-normal leading-[1.1] text-foreground sm:text-[44px]">Why did it happen?</h1>
      {top && topEvent ? (
        <>
          <p className="mt-4 max-w-2xl text-[17px] leading-relaxed text-foreground">
            The trouble appears to have started in <strong className="font-medium">{friendlyName(top.service)}</strong>.
            {topEvent.type === 'deploy' || topEvent.type === 'config_change' ? ' A change was made there shortly before customers were affected.' : ' It struggled before anything else did.'}
          </p>
          <div className="mt-10 grid gap-8 lg:grid-cols-[1fr_minmax(0,380px)]">
            <div className="fl-frame">
              <div className="fl-frame-inner bg-card p-5 sm:p-6">
                <SystemDiagram parts={parts.map((p) => ({ ...p, detail: p.id === top.service ? 'Likely starting point' : affected.has(p.id) ? 'Affected' : 'Not affected' }))} calls={calls} status={status} highlight={top.service} dense={parts.length > 4} />
              </div>
            </div>
            <div>
              <h2 className="text-[13px] text-muted-foreground">What points there</h2>
              <ul className="mt-3 space-y-3 text-[15px] leading-relaxed text-foreground">
                <li><span className="text-muted-foreground">First sign:</span> “{topEvent.message}”</li>
                {lead !== null && lead > 0 ? <li>This happened {durationText(lead)} before customers first saw errors.</li> : null}
                {top.supportingEventIds.length ? <li>{top.supportingEventIds.length} later problems are linked to it by shared requests, timing, and the way the parts depend on each other.</li> : null}
                {top.factors.dependencyPosition > 0 ? <li>{Math.round(top.factors.dependencyPosition * 100)}% of the other affected parts rely on it.</li> : null}
              </ul>
              <p className="mt-5 rounded-xl border border-[var(--color-degraded)]/30 bg-[var(--color-degraded-muted)] px-4 py-3 text-[14px] leading-relaxed text-foreground">
                <strong className="font-medium">A possible cause, not a proven one.</strong> Faultline ranks likely starting points from the evidence; a person should confirm before calling it the root cause.
              </p>
              {analysis.hypotheses.length > 1 ? (
                <div className="mt-5">
                  <h3 className="text-[13px] text-muted-foreground">Other places it could have started</h3>
                  <ul className="mt-2 space-y-1 text-[14px] text-foreground">
                    {analysis.hypotheses.slice(1, 4).map((h) => <li key={h.id}>{friendlyName(h.service)}</li>)}
                  </ul>
                </div>
              ) : null}
            </div>
          </div>

          <div className="mt-10">
            <button type="button" onClick={() => setOpen((o) => !o)} aria-expanded={open} className="inline-flex items-center gap-1.5 text-[14.5px] font-medium text-foreground">
              <ChevronDown className={cn('size-4 transition-transform', open && 'rotate-180')} /> {open ? 'Hide technical evidence' : 'Show technical evidence'}
            </button>
            {open ? (
              <div className="mt-4 overflow-hidden rounded-xl border border-border bg-white">
                <table className="w-full text-[13px]">
                  <caption className="px-4 pt-3 text-left text-[12.5px] text-muted-foreground">Inferred links from the starting event (heuristic scores in 0–1, not probabilities). The ranking factors are in engineering mode.</caption>
                  <thead className="text-left text-[12px] text-muted-foreground"><tr><th className="px-4 py-2 font-normal">Linked event</th><th className="px-2 font-normal">Signals</th><th className="px-4 text-right font-normal">Score</th></tr></thead>
                  <tbody>
                    {edges.map((e) => {
                      const target = byId.get(e.target)
                      return (
                        <tr key={e.id} className="border-t border-border/70 align-top">
                          <td className="px-4 py-2"><span className="font-mono text-[12px] text-muted-foreground">{target?.service}</span><br />{target?.message}<br /><span className="font-mono text-[11px] text-faint">{e.target}</span></td>
                          <td className="px-2 py-2 text-muted-foreground">{e.signals.join(', ')}</td>
                          <td className="px-4 py-2 text-right font-mono tabular">{e.score.toFixed(2)}</td>
                        </tr>
                      )
                    })}
                  </tbody>
                </table>
                <div className="border-t border-border px-4 py-3"><button type="button" onClick={onEngineering} className="text-[13.5px] font-medium text-[var(--color-primary)] hover:underline">Open the full evidence in engineering mode →</button></div>
              </div>
            ) : null}
          </div>
        </>
      ) : (
        <p className="mt-4 text-[16px] text-muted-foreground">The evidence does not point clearly at any one place.</p>
      )}
      <NextBar label="What if?" onNext={onNext} onBack={onBack} />
    </section>
  )
}

function CompareOutcomes({ demo, outcome, markers, onTryAnother, onEngineering }: { demo: DemoScenario; outcome: Outcome; markers: Array<{ atSec: number; label: string; kind: 'change' | 'strain' | 'impact' | 'response' | 'recovery' }>; onTryAnother: () => void; onEngineering: (tab: 'simulate' | 'postmortem') => void }) {
  const ph = usePlayhead(demo.scenario.durationSec, { speed: Math.max(18, demo.scenario.durationSec / 20) })
  useEffect(() => {
    ph.seek(Math.max(0, outcome.atSec - 20))
    ph.play()
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [outcome])
  const verdict = outcome.comparison.overall
  return (
    <section aria-labelledby="cmp-h">
      <p className="fl-eyebrow">Step 4</p>
      <h1 id="cmp-h" className="mt-3 max-w-3xl text-[34px] font-normal leading-[1.1] text-foreground sm:text-[44px]">
        {verdict === 'better' ? 'This decision would have helped.' : verdict === 'worse' ? 'This decision would have made it worse.' : verdict === 'mixed' ? 'This decision helps in some ways, not others.' : 'This decision barely changes the outcome.'}
      </h1>
      <p className="mt-4 text-[15px] text-muted-foreground">Your decision: <span className="text-[var(--color-sim)]">{outcome.label}</span>, at {fmt(outcome.atSec)}.</p>
      <div className="mt-8 fl-frame">
        <div className="fl-frame-inner bg-card p-5 sm:p-7">
          <FaultlineTimeline durationSec={demo.scenario.durationSec} baseline={outcome.baseline.samples} branch={outcome.branch.samples} decisionSec={outcome.atSec} t={ph.t} onSeek={ph.seek} markers={markers} branchLabel={outcome.label} />
          <div className="mt-4 flex items-center gap-2">
            <button type="button" onClick={ph.playing ? ph.pause : ph.play} className="fl-btn-quiet inline-flex h-9 items-center gap-1.5 rounded-lg px-3 text-[13.5px]">{ph.playing ? <Pause className="size-4" /> : <Play className="size-4" />} {ph.playing ? 'Pause' : 'Replay both timelines'}</button>
          </div>
        </div>
      </div>
      <div className="mt-8">
        <OutcomeComparison
          outcome={outcome}
          actions={
            <>
              <button type="button" onClick={onTryAnother} className="fl-cta inline-flex h-10 items-center gap-1.5 rounded-xl px-4 text-[14px] font-medium">Try another decision</button>
              <button type="button" onClick={() => onEngineering('simulate')} className="fl-btn-quiet inline-flex h-10 items-center rounded-xl px-4 text-[14px]">View technical details</button>
              <button type="button" onClick={() => onEngineering('postmortem')} className="fl-btn-quiet inline-flex h-10 items-center rounded-xl px-4 text-[14px]">Create incident report</button>
              <Link to="/demo" className="fl-btn-quiet inline-flex h-10 items-center rounded-xl px-4 text-[14px]">Explore another scenario</Link>
              <a href={IS_STANDALONE ? `${CANONICAL_URL}/incidents/new` : '/incidents/new'} className="inline-flex h-10 items-center gap-1 rounded-xl px-3 text-[14px] text-muted-foreground hover:text-foreground">Analyze your own incident <ArrowRight className="size-4" /></a>
            </>
          }
        />
      </div>
    </section>
  )
}

function Stat({ label, value, tone }: { label: string; value: string; tone: 'ok' | 'warn' | 'fault' }) {
  return (
    <div className="rounded-xl bg-background px-4 py-3">
      <div className="text-[12.5px] text-muted-foreground">{label}</div>
      <div className={cn('mt-1 text-[22px] font-medium tabular', tone === 'fault' ? 'text-[var(--color-fault)]' : tone === 'warn' ? 'text-[var(--color-degraded)]' : 'text-foreground')}>{value}</div>
    </div>
  )
}

function NextBar({ label, onNext, onBack }: { label: string; onNext: () => void; onBack?: () => void }) {
  return (
    <div className="mt-14 flex items-center justify-between border-t border-border pt-6">
      {onBack ? <button type="button" onClick={onBack} className="inline-flex h-10 items-center gap-1.5 rounded-xl px-3 text-[14.5px] text-muted-foreground hover:text-foreground"><ArrowLeft className="size-4" /> Back</button> : <span />}
      <button type="button" onClick={() => { onNext(); window.scrollTo({ top: 0, behavior: 'smooth' }) }} className="fl-cta inline-flex h-11 items-center gap-2 rounded-xl px-5 text-[15px] font-medium">Next: {label} <ArrowRight className="size-4" /></button>
    </div>
  )
}
