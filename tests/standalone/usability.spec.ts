import { expect, test, type Page } from '@playwright/test'

const noHorizontalScroll = (page: Page) => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)

test.describe('a first-time visitor', () => {
  test('understands what Faultline is and can start the demo without an account', async ({ page }) => {
    await page.goto('/')
    await expect(page.getByRole('heading', { level: 1 })).toContainText('Understand what broke.')
    await expect(page.getByText('No account needed.')).toBeVisible()
    // The live hero is labeled as synthetic, never presented as a real outage.
    await expect(page.getByText('Synthetic example, simulated live in your browser')).toBeVisible()
    await page.getByRole('link', { name: 'Try the demo' }).first().click()
    await expect(page).toHaveURL(/\/demo$/)
    await expect(page.getByRole('heading', { level: 1, name: 'Pick an outage to explore.' })).toBeVisible()
  })

  test('walks the guided demo from what happened to a compared outcome', async ({ page }) => {
    await page.goto('/demo/checkout-cascade')

    // Step 1: plain-language headline, synthetic label, measured impact.
    await expect(page.getByRole('heading', { level: 1, name: 'An online store suddenly stops accepting orders.' })).toBeVisible()
    await expect(page.getByText(/Synthetic example: generated by Faultline/)).toBeVisible()
    await expect(page.getByText(/of customer requests failed/)).toBeVisible()

    // Step 2: a likely starting point, framed as unproven.
    await page.getByRole('button', { name: /Why did it happen\?/ }).last().click()
    await expect(page.getByRole('heading', { level: 1, name: 'Why did it happen?' })).toBeVisible()
    await expect(page.getByText('A possible cause, not a proven one.')).toBeVisible()

    // Step 3 to 4: explore a decision; the verdict comes from a real run.
    await page.getByRole('button', { name: /What if\?/ }).last().click()
    await expect(page.getByRole('heading', { level: 1, name: 'What would you have done differently?' })).toBeVisible()
    await page.getByRole('button', { name: 'Explore this outcome' }).click()
    await expect(page.getByRole('heading', { level: 1, name: /^This decision would have/ })).toBeVisible()
    await expect(page.getByText('Successful requests')).toBeVisible()
    await expect(page.getByText(/Simulated, not recorded/)).toBeVisible()
  })

  test('switches between Guided and Engineering modes without losing the incident', async ({ page }) => {
    await page.goto('/demo/retry-storm')
    await expect(page.getByRole('heading', { level: 1 })).toContainText('A social app slows down')
    await page.getByRole('button', { name: 'Engineering' }).click()
    await expect(page).toHaveURL(/mode=engineering/)
    await expect(page.getByRole('heading', { level: 1, name: 'The Retry Storm' })).toBeVisible()
    await page.getByRole('button', { name: 'Guided' }).click()
    await expect(page.getByRole('heading', { level: 1 })).toContainText('A social app slows down')
  })

  test('can drive the timeline with the keyboard alone', async ({ page }) => {
    await page.goto('/demo/checkout-cascade')
    const slider = page.getByRole('slider', { name: /^Timeline\./ }).first()
    await expect(slider).toBeVisible()
    await slider.focus()
    await page.keyboard.press('End')
    const max = await slider.getAttribute('aria-valuemax')
    await expect(slider).toHaveAttribute('aria-valuenow', max!)
    await page.keyboard.press('Home')
    await expect(slider).toHaveAttribute('aria-valuenow', '0')
    await page.keyboard.press('Shift+ArrowRight')
    await expect(slider).toHaveAttribute('aria-valuenow', '10')
  })

  test('breaks a system on purpose in the experiment lab and sees results', async ({ page }) => {
    await page.goto('/lab')
    await page.getByRole('button', { name: 'Banking application' }).click()
    await expect(page.getByText('Customers sign in and send money.')).toBeVisible()
    await page.getByRole('button', { name: 'An outside service stops responding' }).click()
    await expect(page.getByText(/fraud-check stops responding/)).toBeVisible()
    await page.getByRole('button', { name: 'Run simulation' }).click()
    await expect(page.getByText('Success rate', { exact: true })).toBeVisible()
  })

  test('reads the privacy and security pages linked from the footer', async ({ page }) => {
    for (const [path, title] of [['/docs/privacy', /privacy/i], ['/docs/security', /security/i]] as const) {
      await page.goto(path)
      await expect(page.getByRole('heading', { level: 1 })).toHaveText(title)
    }
  })
})

test.describe('on a phone', () => {
  test.use({ viewport: { width: 390, height: 844 } })

  for (const path of ['/', '/demo', '/demo/checkout-cascade', '/lab', '/docs/simulation']) {
    test(`${path} fits the screen without sideways scrolling`, async ({ page }) => {
      await page.goto(path)
      await page.waitForLoadState('networkidle')
      expect(await noHorizontalScroll(page)).toBeLessThanOrEqual(1)
    })
  }
})
